    import os, sys
    sys.path.insert(0, os.path.dirname(__file__))
    import build_db
    z, sheets = build_db.load_workbook()
    z.close()
    names = set()
    for s in FURNITURE_CATEGORIES:
        hdr = sheets[s][0]
        idx = {h: i for i, h in enumerate(hdr) if h}
        name_i = idx.get("Name", 0)
        for r in sheets[s][1:]:
            if r and name_i < len(r) and r[name_i]:
                names.add(r[name_i].strip())
    rows = sorted((n, classify(n)) for n in names)
    os.makedirs("res", exist_ok=True)
    with open("res/furniture_types.tsv", "w") as f:
        f.write("name\tpath\n")
        for n, path in rows:
            f.write(f"{n}\t{'/'.join(path)}\n")
    from collections import Counter
    tops = Counter(p[0] for _, p in rows)
    print(f"cataloged {len(rows)} items")
    print("\ntop-level categories:")
    for t, n in tops.most_common():
        print(f"  {t:14s} {n}")
    print("\nsample 3rd-level paths:")
    seen = set()
    for _, p in rows:
        if len(p) >= 3 and p[:2] not in seen:
            seen.add(p[:2])
            print("  ", "/".join(p))
    others = [n for n, p in rows if p[0] == "Other"]
    print(f"\nunclassified ({len(others)}):")
    for n in others:
        print("  ", n)
