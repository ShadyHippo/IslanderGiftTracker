def classify(name):
    """Return the category path (1-3 levels) for an item name.

    e.g. ('Kitchen','Appliance','Fridge') or ('Decoration','Instrument','Guitar').
    The tree is implicit: an item inherits every ancestor, so selecting
    'Kitchen' includes 'Kitchen/Appliance', 'Kitchen/Cups', etc.
    """
    key = name.strip().lower()
    if key in OVERRIDES:
        path = list(OVERRIDES[key])
    else:
        path = None
        for keywords, t in KEYWORD_RULES:
            if any(k in key for k in keywords):
                path = list(t)
                break
        if path is None:
            return ("Other", "Other")
    # 3rd level: refine by keyword when the parent allows it.
    parent = tuple(path)
    if parent in THIRD:
        for kw, leaf in THIRD[parent].items():
            if kw in key:
                return (*path, leaf)
    return tuple(path)

def type_for(name):
    """Backward-compat: top-level category only."""
    return classify(name)[0]

